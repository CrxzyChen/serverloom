const { contextBridge, ipcRenderer, webUtils } = require('electron')
contextBridge.exposeInMainWorld('servers', {
  updateSnapshot: () => ipcRenderer.invoke('updates:snapshot'),
  updateSettings: value => ipcRenderer.invoke('updates:settings', value),
  checkUpdate: () => ipcRenderer.invoke('updates:check'),
  downloadUpdate: () => ipcRenderer.invoke('updates:download'),
  installUpdate: () => ipcRenderer.invoke('updates:install'),
  cancelUpdate: () => ipcRenderer.invoke('updates:cancel'),
  openRelease: () => ipcRenderer.invoke('updates:release'),
  schedulerSnapshot: () => ipcRenderer.invoke('scheduler:snapshot'),
  saveSchedule: value => ipcRenderer.invoke('scheduler:save', value),
  removeSchedule: id => ipcRenderer.invoke('scheduler:remove', id),
  enableSchedule: (id, enabled) => ipcRenderer.invoke('scheduler:enable', {id, enabled}),
  pauseScheduler: value => ipcRenderer.invoke('scheduler:pause', value),
  runSchedule: id => ipcRenderer.invoke('scheduler:run', id),
  cancelRun: id => ipcRenderer.invoke('scheduler:cancel', id),
  desktopSettings: value => ipcRenderer.invoke('desktop:settings', value),
  quit: () => ipcRenderer.invoke('desktop:quit'),
  load: () => ipcRenderer.invoke('data:load'),
  windowControl: action => ipcRenderer.invoke('window:control', action),
  saveServer: value => ipcRenderer.invoke('server:save', value),
  saveGroup: value => ipcRenderer.invoke('group:save', value),
  removeGroup: id => ipcRenderer.invoke('group:remove', id),
  reorderGroup: (id, direction) => ipcRenderer.invoke('group:reorder', { id, direction }),
  moveServer: (id, groupId) => ipcRenderer.invoke('server:moveGroup', { id, groupId }),
  selectMigration: file => ipcRenderer.invoke('migration:select', file ? webUtils.getPathForFile(file) : undefined),
  previewMigration: value => ipcRenderer.invoke('migration:preview', value),
  commitMigration: value => ipcRenderer.invoke('migration:commit', value),
  discardMigration: token => ipcRenderer.invoke('migration:discard', token),
  exportMigration: value => ipcRenderer.invoke('migration:export', value),
  selectKey: () => ipcRenderer.invoke('server:selectKey'),
  testConnection: id => ipcRenderer.invoke('server:test', id),
  openTool: value => ipcRenderer.invoke('workbench:open', value),
  closeTool: id => ipcRenderer.invoke('workbench:close', id),
  terminalInput: (id, data) => ipcRenderer.invoke('workbench:input', { id, data }),
  terminalResize: (id, cols, rows) => ipcRenderer.invoke('workbench:resize', { id, cols, rows }),
  listFiles: (id, path) => ipcRenderer.invoke('workbench:list', { id, path }),
  previewFile: (id, path) => ipcRenderer.invoke('workbench:preview', { id, path }),
  transferFile: (id, path, upload) => ipcRenderer.invoke('workbench:transfer', { id, path, upload }),
  bandwidth: id => ipcRenderer.invoke('workbench:bandwidth', id),
  copyText: text => ipcRenderer.invoke('text:copy', text),
  openLink: url => ipcRenderer.invoke('link:open', url),
  start: () => ipcRenderer.invoke('runtime:start'),
  stop: () => ipcRenderer.invoke('runtime:stop'),
  account: () => ipcRenderer.invoke('runtime:account'),
  login: () => ipcRenderer.invoke('runtime:login'),
  catalog: refresh => ipcRenderer.invoke('copilot:catalog', refresh),
  limits: () => ipcRenderer.invoke('copilot:limits'),
  saveCopilotSettings: value => ipcRenderer.invoke('copilot:settings', value),
  copilotSnapshot: id => ipcRenderer.invoke('copilot:snapshot', id),
  answerQuestion: value => ipcRenderer.invoke('copilot:answer', value),
  addAttachments: (conversationId, files) => ipcRenderer.invoke('attachments:add', { conversationId, files: files?.map(file => ({ path: webUtils.getPathForFile(file) })) }),
  pasteAttachment: (conversationId, png) => ipcRenderer.invoke('attachments:add', { conversationId, files: [{ png }] }),
  previewAttachment: value => ipcRenderer.invoke('attachments:preview', value),
  removeAttachment: value => ipcRenderer.invoke('attachments:remove', value),
  send: value => ipcRenderer.invoke('runtime:send', value),
  interrupt: () => ipcRenderer.invoke('runtime:interrupt'),
  approve: (id, decision) => ipcRenderer.invoke('runtime:approve', { id, decision }),
  onEvent: callback => { const listener = (_, event) => callback(event); ipcRenderer.on('runtime:event', listener); return () => ipcRenderer.removeListener('runtime:event', listener) }
})
