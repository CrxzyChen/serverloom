import { _electron as electron } from 'playwright'
import { mkdir, mkdtemp, writeFile } from 'node:fs/promises'
import { resolve, join } from 'node:path'
import assert from 'node:assert/strict'
await mkdir('artifacts', { recursive: true })
const data = await mkdtemp(resolve('artifacts/smoke-'))
const app = await electron.launch({ args: ['.'], env: { ...process.env, SERVERS_TEST_DATA: data, SERVERS_DEV: '0' } })
try {
  const page = await app.firstWindow()
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.getByRole('heading', { name: '选择服务器，开始工作。' }).waitFor()
  await page.waitForFunction(async () => (await window.servers.load()).runtime.state === 'ready', undefined, { timeout: 45000 })
  await page.screenshot({ path: 'artifacts/workspace-empty.png' })
  await page.getByRole('button', { name: '添加服务器', exact: true }).first().click()
  await page.getByLabel('服务器名称', { exact: true }).fill('香港生产节点 · 测试资产')
  await page.getByLabel('主机地址', { exact: true }).fill('hk.example.invalid')
  await page.getByLabel('用途与备注', { exact: true }).fill('用于客户端测试，不是真实服务器。')
  await page.getByLabel('认证方式', { exact: true }).selectOption('privateKey')
  assert.equal(await page.getByRole('button', { name: '选择私钥文件', exact: true }).isVisible(), true)
  await page.screenshot({ path: 'artifacts/server-form.png' })
  await page.getByRole('button', { name: '保存服务器', exact: true }).click()
  await page.getByRole('heading', { name: '香港生产节点 · 测试资产', exact: true }).waitFor()
  await page.getByText('待补全：SSH 用户名、私钥文件', { exact: true }).waitFor()
  await page.reload()
  await page.getByRole('button', { name: /香港生产节点 · 测试资产 hk.example.invalid/ }).click()
  await page.getByRole('button', { name: '制定巡检计划', exact: true }).click()
  assert.match(await page.getByRole('textbox', { name: '发送给 Codex 的任务' }).inputValue(), /巡检/)
  await page.screenshot({ path: 'artifacts/workspace-server.png' })
  await page.getByRole('button', { name: '运行时设置', exact: true }).click()
  await page.getByRole('button', { name: '停止运行时', exact: true }).waitFor({ timeout: 45000 })
  assert.equal(await page.getByRole('main').getByRole('button', { name: '登录 ChatGPT', exact: true }).isEnabled(), true)
  await page.screenshot({ path: 'artifacts/runtime-ready.png' })
  await page.getByRole('button', { name: '停止运行时', exact: true }).click()
  await page.reload()
  assert.equal(await page.evaluate(async () => (await window.servers.load()).runtime.state), 'stopped')
  await page.getByRole('button', { name: /操作记录/ }).click()
  await page.getByRole('main').getByText('保存服务器', { exact: true }).waitFor()
  await page.screenshot({ path: 'artifacts/history.png' })
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(960, 720))
  await page.getByRole('button', { name: '运维工作台', exact: true }).click()
  await page.screenshot({ path: 'artifacts/workspace-narrow.png' })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.setZoomFactor(1.5))
  await page.getByRole('button', { name: '切换侧边栏', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.statusbar').getBoundingClientRect().bottom <= innerHeight + 1)
  const zoomImage = await app.evaluate(async ({ BrowserWindow }) => (await BrowserWindow.getAllWindows()[0].webContents.capturePage()).toDataURL())
  await writeFile('artifacts/workspace-150.png', Buffer.from(zoomImage.split(',')[1], 'base64'))
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  assert.equal(await page.evaluate(() => { const rect = document.querySelector('.send-button').getBoundingClientRect(); return rect.right <= innerWidth && rect.bottom <= innerHeight }), true)
  assert.deepEqual(errors, [])
  console.log('PASS: automatic runtime startup, renderer reload without restart, manual stop, server persistence, history and zoom')
} finally { await app.close() }
