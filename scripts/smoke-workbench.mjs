import { _electron as electron } from 'playwright'
import { mkdir, mkdtemp, writeFile } from 'node:fs/promises'
import { resolve, join } from 'node:path'
import assert from 'node:assert/strict'
await mkdir('artifacts', { recursive: true })
const directory = await mkdtemp(resolve('artifacts/workbench-ui-'))
if(!process.env.TEST_SSH_HOST||!process.env.TEST_SSH_USER||!process.env.TEST_SSH_KEY)throw new Error('Set TEST_SSH_HOST, TEST_SSH_USER and TEST_SSH_KEY for this opt-in live test')
const server = { id: 'home-server', name: 'home-server', host: process.env.TEST_SSH_HOST, user: process.env.TEST_SSH_USER, port: 22, authType: 'privateKey', privateKeyPath: process.env.TEST_SSH_KEY, configStatus: 'configured', missingFields: [], group: '局域网' }
await writeFile(join(directory, 'servers.json'), JSON.stringify({ servers: [server, { ...server, id: 'backup', name: 'backup', host: '192.0.2.1' }], history: [] }))
const app = await electron.launch({ args: ['.'], env: { ...process.env, SERVERS_TEST_DATA: directory, SERVERS_DEV: '0' } })
try {
  const page = await app.firstWindow(), errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.getByRole('button', { name: `home-server ${server.host}`, exact: true }).click()
  await page.locator('.workspace-home:visible').getByRole('button', { name: '新建 Copilot 对话' }).click()
  await page.getByRole('heading', { name: '开始管理 home-server' }).waitFor()
  await page.getByRole('textbox', { name: '发送给 Codex 的任务' }).fill('检查当前服务器')
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('servers-workbench') || '{}').sessions?.length === 2)
  const first = await page.evaluate(() => JSON.parse(localStorage.getItem('servers-workbench')).conversationId)
  await app.evaluate(({ BrowserWindow }, conversationId) => BrowserWindow.getAllWindows()[0].webContents.send('runtime:event', { method: 'item/agentMessage/delta', conversationId, params: { itemId: 'ui-report', delta: '这是 **home-server** 的界面验证对话。\n\n可以同时查看终端和文件，工具与对话各自保持服务器上下文。' } }), first)
  await page.getByText('的界面验证对话。', { exact: false }).waitFor()
  await page.getByRole('button', { name: 'backup 192.0.2.1', exact: true }).click()
  assert.match(await page.locator('.chat-context').innerText(), /home-server/)
  await page.locator('.workspace-home:visible').getByRole('button', { name: '新建 Copilot 对话' }).click()
  await app.evaluate(({ BrowserWindow }, conversationId) => BrowserWindow.getAllWindows()[0].webContents.send('runtime:event', { method: 'item/agentMessage/delta', conversationId, params: { itemId: 'ui-report', delta: '\n\n后台消息仍归属于原会话。' } }), first)
  assert.equal(await page.getByText('后台消息仍归属于原会话。', { exact: false }).isVisible(), false)
  await page.getByRole('button', { name: '切换会话列表' }).click()
  await page.locator('.session-row').filter({ hasText: 'home-server' }).click()
  await page.getByText('后台消息仍归属于原会话。', { exact: false }).waitFor()
  assert.equal(await page.getByRole('textbox', { name: '发送给 Codex 的任务' }).inputValue(), '检查当前服务器')
  await page.getByRole('button', { name: `home-server ${server.host}`, exact: true }).click()
  await page.getByRole('button', { name: '关闭 概览 · home-server', exact: true }).click()
  await page.getByRole('button', { name: `home-server ${server.host}`, exact: true }).dblclick()
  assert.equal(await page.getByRole('tab', { name: '概览 · home-server', exact: true }).count(), 0)
  await page.locator('.tool-status').getByText('已连接', { exact: true }).waitFor({ timeout: 20000 })
  await page.locator('.terminal-host .xterm-helper-textarea').focus()
  await page.keyboard.type("unset HISTFILE; printf 'WORKSPACE_TERMINAL_READY\\n'; uptime")
  await page.keyboard.press('Enter')
  await page.waitForFunction(() => document.querySelector('.xterm-screen') !== null)
  await page.screenshot({ path: 'artifacts/workbench-terminal.png' })
  await page.getByRole('button', { name: '运维工作台', exact: true }).click()
  await page.getByRole('button', { name: `home-server ${server.host}`, exact: true }).click()
  await page.getByRole('button', { name: /文件管理器 浏览/ }).click()
  await page.waitForFunction(() => /个项目/.test(document.querySelector('.files-pane .tool-caption')?.textContent || ''))
  await page.getByRole('textbox', { name: '服务器目录' }).fill('/etc')
  await page.getByRole('textbox', { name: '服务器目录' }).press('Enter')
  await page.getByRole('button', { name: /^os-release/ }).waitFor({ timeout: 20000 })
  await page.getByRole('button', { name: /^os-release/ }).click()
  await page.locator('.file-preview pre').getByText('Ubuntu', { exact: false }).waitFor()
  await page.screenshot({ path: 'artifacts/workbench-files.png' })
  await page.getByRole('button', { name: '收起会话列表' }).click()
  const splitter = page.getByRole('separator', { name: '调整 Copilot 宽度' })
  const before = await splitter.getAttribute('aria-valuenow')
  await splitter.focus(); await page.keyboard.press('ArrowLeft')
  assert.equal(Number(await splitter.getAttribute('aria-valuenow')), Number(before) + 20)
  await page.getByRole('button', { name: '运行时设置', exact: true }).click()
  await page.getByRole('tab', { name: 'SSH 终端 · home-server', exact: true }).click()
  assert.equal(await page.locator('.tool-status').getByText('已连接', { exact: true }).isVisible(), true)
  await page.getByRole('tab', { name: '概览 · home-server', exact: true }).click()
  await page.getByRole('button', { name: /带宽监控 真实/ }).click()
  await page.locator('.bandwidth-body tbody tr').first().waitFor({ timeout: 20000 })
  await page.screenshot({ path: 'artifacts/workbench-bandwidth.png' })
  await page.getByRole('button', { name: '展开 Copilot' }).click()
  assert.equal(await page.locator('.center-workspace').isVisible(), false)
  await page.getByRole('button', { name: '还原 Copilot' }).click()
  await page.getByRole('button', { name: '收起 Copilot', exact: true }).click()
  assert.equal(await page.locator('.center-workspace').isVisible(), true)
  await page.getByRole('button', { name: '切换 Copilot 面板' }).click()
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(960, 720))
  await page.getByRole('button', { name: '切换侧边栏' }).click()
  await page.screenshot({ path: 'artifacts/workbench-compact.png' })
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.setZoomFactor(1.5))
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  assert.equal(await page.evaluate(() => document.querySelector('.send-button').getBoundingClientRect().right <= innerWidth), true)
  const zoomImage = await app.evaluate(async ({ BrowserWindow }) => (await BrowserWindow.getAllWindows()[0].webContents.capturePage()).toDataURL())
  await writeFile('artifacts/workbench-zoom.png', Buffer.from(zoomImage.split(',')[1], 'base64'))
  await page.reload()
  await page.getByText('后台消息仍归属于原会话。', { exact: false }).waitFor()
  assert.deepEqual(errors, [])
  console.log('PASS: live SSH/files/bandwidth, stable server binding, independent sessions, drafts and messages restored, tab retention, splitters, collapse, expand, narrow layout and zoom')
} finally { await app.close() }
